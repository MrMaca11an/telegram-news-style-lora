def run():
    audit_rows=[]; lines=['# аудиторская ведомость 50 оригинальных обучающих пар','','это технический аудит для редакторской проверки. флаги не означают автоматически доказанную галлюцинацию; референсы сами могут содержать недостоверные или гиперболизированные утверждения.','','исходные данные не изменены.']
    for style in ('type1','type2'):
        src=read_jsonl(ROOT/f'data/raw/train_{style}.jsonl')
        assert len(src)==25 and len(NOTES[style])==25
        lines += ['',f'## {style} (25 записей)','']
        for i,row in enumerate(src,1):
            fmt=output_checks(style,row['output'])
            incoming=numbers(row['input']); outgoing=numbers(row['output'])
            new=sorted(outgoing-incoming)
            issues=[]
            if new: issues.append('цифры в output не обнаружены в input: '+', '.join(new))
            if not fmt['pass']: issues.append('формат не полностью совпадает с ожидаемым')
            if 'type1'==style and not fmt['signature']: issues.append('нет подписи канала')
            if 'type2'==style and not fmt['starts_emoji']: issues.append('нет стартового эмодзи')
            audit_rows.append({'style':style,'row_id':i,'instruction':row['instruction'],
                               'input':row['input'],'output':row['output'],
                               'style_format':fmt,'new_numeric_literals':new,
                               'automatic_flags':issues,'human_review_note':NOTES[style][i-1],
                               'human_fact_check_completed':False})
            in_preview = re.sub(r'\s+', ' ', row['input'])[:118]
            out_preview = re.sub(r'\s+', ' ', row['output'])[:118]
            lines += [f'### {style}, строка {i}',f'- исходник: {in_preview}…',
                      f'- эталон: {out_preview}…',
                      f'- проверка: {NOTES[style][i-1]}',
                      f'- автоматические замечания: {"; ".join(issues) if issues else "нет (это не гарантия фактической точности)"}','']
    write_jsonl(ROOT/'reports/audit_all_50.jsonl',audit_rows)
    (ROOT/'reports/audit_all_50.md').write_text('\n'.join(lines)+'\n',encoding='utf8')
    print('audited',len(audit_rows),'source/target rows; manual review outstanding')
    print('numeric mismatches:',sum(bool(r['new_numeric_literals']) for r in audit_rows))

if __name__=='__main__':run()
